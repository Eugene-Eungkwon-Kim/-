_CODE_TO_NAME = {code: name for name, code in SGG_CODES.items()}


def get_all_sgg_codes() -> list[str]:
    return list(SGG_CODES.values())


def sido_of(sgg_code: str) -> str:
    """코드 → 시/도. 모르는 코드면 빈 문자열."""
    name = _CODE_TO_NAME.get(sgg_code, "")
    return name.split(" ", 1)[0] if name else ""


def sigungu_of(sgg_code: str) -> str:
    """코드 → 시/군/구. 모르는 코드면 빈 문자열."""
    name = _CODE_TO_NAME.get(sgg_code, "")
    parts = name.split(" ", 1)
    return parts[1] if len(parts) == 2 else ""
